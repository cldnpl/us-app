// "How Well Do You Know Me": per question one partner is the subject (answers
// honestly) and the other guesses. Subject alternates by question index using
// a stable ordering of the two user ids, so both devices agree on roles.
//
// Each pack has a per-couple "round" (see packRoundStore): a generation number
// + the current set of questions + a seenBy list. Answers live in quiz_answers
// under the composite quiz_id `hwdykm:<packID>:g<gen>` so old rounds stay in
// the DB (searchable, but ignored). When both partners have opened results and
// both have answered every question, the round rotates: gen++, a fresh batch
// of questions is generated by Claude (falling back to the seed catalog), and
// the pack becomes playable again with brand-new material.

func hwdykmAnswerKey(packID string, gen int) string {
	return fmt.Sprintf("hwdykm:%s:g%d", packID, gen)
}
func hwdykmRoundGameType(packID string) string { return "hwdykm_pack:" + packID }

type hwdykmRoundContent struct {
	Questions []hwdykmQuestion `json:"questions"`
}

type hwdykmPackSummary struct {
	ID            string `json:"id"`
	Title         string `json:"title"`
	Icon          string `json:"icon"`
	ColorKey      string `json:"colorKey"`
	Tag           string `json:"tag"`
	QuestionCount int    `json:"questionCount"`
	MyDone        bool   `json:"myDone"`
	PartnerDone   bool   `json:"partnerDone"`
	BothDone      bool   `json:"bothDone"`
}

type hwdykmQuestionView struct {
	ID           string         `json:"id"`
	Prompt       string         `json:"prompt"`
	Options      []hwdykmOption `json:"options"`
	SubjectIsMe  bool           `json:"subjectIsMe"` // true → I answer honestly; false → I guess my partner
	MyAnswer     *string        `json:"myAnswer"`
	HonestAnswer *string        `json:"honestAnswer"`
	Guess        *string        `json:"guess"`
	Matched      bool           `json:"matched"`
}

type hwdykmPackDetail struct {
	ID        string               `json:"id"`
	Title     string               `json:"title"`
	Icon      string               `json:"icon"`
	ColorKey  string               `json:"colorKey"`
	Tag       string               `json:"tag"`
	MyDone    bool                 `json:"myDone"`
	BothDone  bool                 `json:"bothDone"`
	Score     int                  `json:"score"`
	Questions []hwdykmQuestionView `json:"questions"`
}

// orderedIDs returns the two user ids in a stable order (subject A, subject B).
func orderedIDs(a, b string) (string, string) {
	if b < a {
		return b, a
	}
	return a, b
}

// ---- helpers -----------------------------------------------------------------

// hwdykmRoundQuestions returns the couple's questions for the current round of
// a pack, creating the round on first access. Falls back to the seed catalog
// when either the round hasn't been rotated yet or the persisted content looks
// corrupt.
func (d Deps) hwdykmRoundQuestions(ctx context.Context, coupleID string, seed hwdykmPack, lang string) (int, []hwdykmQuestion, packRoundState, *packRoundStore, error) {
	rs := d.packRound(coupleID, hwdykmRoundGameType(seed.ID))
	if err := rs.load(ctx); err != nil {
		return 0, nil, packRoundState{}, nil, err
	}
	st := rs.current()
	if st.Generation == 0 {
		content := hwdykmRoundContent{Questions: seed.Questions}
		raw, _ := json.Marshal(content)
		newSt, err := rs.initialize(ctx, "", raw)
		if err != nil {
			return 0, nil, packRoundState{}, nil, err
		}
		return newSt.Generation, seed.Questions, newSt, rs, nil
	}
	var content hwdykmRoundContent
	_ = json.Unmarshal(st.Content, &content)
	if len(content.Questions) < len(seed.Questions) {
		content.Questions = seed.Questions
	}
	return st.Generation, content.Questions, st, rs, nil
}

func (d Deps) generateFreshHwdykmQuestions(ctx context.Context, seed hwdykmPack, lang string, nextGen int) []hwdykmQuestion {
	gen := generator.New(d.Config.AnthropicAPIKey, d.Config.AnthropicModel)
	avoid := make([]string, 0, len(seed.Questions))
	fallback := make([]generator.HwdykmQuestion, 0, len(seed.Questions))
	for _, q := range seed.Questions {
		avoid = append(avoid, q.Prompt)
		opts := make([]string, 0, len(q.Options))
		for _, o := range q.Options {
			opts = append(opts, o.Label)
		}
		fallback = append(fallback, generator.HwdykmQuestion{Prompt: q.Prompt, Options: opts})
	}
	description := ""
	if seed.Tag != "" {
		description = "Tone: " + seed.Tag + "."
	}
	fresh := gen.HwdykmQuestions(ctx, seed.Title, description, len(seed.Questions), avoid, lang, fallback)
	out := make([]hwdykmQuestion, 0, len(fresh))
	for i, q := range fresh {
		out = append(out, hwdykmQuestion{
			ID:      fmt.Sprintf("%s_g%d_q%d", seed.ID, nextGen, i+1),
			Prompt:  q.Prompt,
			Options: hopts(q.Options...),
		})
	}
	return out
}

