// GET /v1/games/hwdykm/packs
func (d Deps) handleListHwdykmPacks(w http.ResponseWriter, r *http.Request) {
	userID, ok := d.authedUser(w, r)
	if !ok {
		return
	}
	c, ok := d.gameCouple(w, r, userID)
	if !ok {
		return
	}
	partner, _ := d.Store.GetPartner(r.Context(), c.ID, userID)

	keys, err := d.Store.GetQuizAnswerKeys(r.Context(), c.ID)
	if err != nil {
		d.serverError(w, "hwdykm: keys", err)
		return
	}
	counts := make(map[string]map[string]int)
	for _, k := range keys {
		if counts[k.QuizID] == nil {
			counts[k.QuizID] = make(map[string]int)
		}
		counts[k.QuizID][k.UserID]++
	}

	packs := hwdykmPacksFor(langParam(r))
	out := make([]hwdykmPackSummary, 0, len(packs))
	for _, p := range packs {
		gen, questions, _, _, rerr := d.hwdykmRoundQuestions(r.Context(), c.ID, p, langParam(r))
		if rerr != nil {
			d.serverError(w, "hwdykm: round", rerr)
			return
		}
		total := len(questions)
		key := hwdykmAnswerKey(p.ID, gen)
		myDone := counts[key][userID] >= total && total > 0
		partnerDone := partner.ID != "" && counts[key][partner.ID] >= total && total > 0
		out = append(out, hwdykmPackSummary{
			ID: p.ID, Title: p.Title, Icon: p.Icon, ColorKey: p.ColorKey, Tag: p.Tag,
			QuestionCount: total, MyDone: myDone, PartnerDone: partnerDone,
			BothDone: myDone && partnerDone,
		})
	}
	writeJSON(w, http.StatusOK, map[string]any{"packs": out})
}

// GET /v1/games/hwdykm/packs/{id}
func (d Deps) handleGetHwdykmPack(w http.ResponseWriter, r *http.Request) {
	userID, ok := d.authedUser(w, r)
	if !ok {
		return
	}
	c, ok := d.gameCouple(w, r, userID)
	if !ok {
		return
	}
	pack, found := findHwdykmPackIn(hwdykmPacksFor(langParam(r)), chi.URLParam(r, "id"))
	if !found {
		writeError(w, http.StatusNotFound, "unknown_pack", "unknown pack")
		return
	}
	partner, _ := d.Store.GetPartner(r.Context(), c.ID, userID)
	aID, bID := orderedIDs(userID, partner.ID)

	gen, questions, _, _, err := d.hwdykmRoundQuestions(r.Context(), c.ID, pack, langParam(r))
	if err != nil {
		d.serverError(w, "hwdykm: round", err)
		return
	}
	quizID := hwdykmAnswerKey(pack.ID, gen)

	answers, err := d.Store.GetQuizAnswers(r.Context(), c.ID, quizID)
	if err != nil {
		d.serverError(w, "hwdykm: answers", err)
		return
	}
	byUser := make(map[string]map[string]string)
	for _, a := range answers {
		if byUser[a.UserID] == nil {
			byUser[a.UserID] = make(map[string]string)
		}
		byUser[a.UserID][a.QuestionID] = a.Answer
	}

	myDone, partnerDone := true, true
	for _, q := range questions {
		if byUser[userID][q.ID] == "" {
			myDone = false
		}
		if partner.ID == "" || byUser[partner.ID][q.ID] == "" {
			partnerDone = false
		}
	}
	bothDone := myDone && partnerDone

	views := make([]hwdykmQuestionView, 0, len(questions))
	matches := 0
	for i, q := range questions {
		subject := aID
		if i%2 == 1 {
			subject = bID
		}
		guesser := aID
		if subject == aID {
			guesser = bID
		}
		v := hwdykmQuestionView{ID: q.ID, Prompt: q.Prompt, Options: q.Options, SubjectIsMe: subject == userID}
		if mine, ok := byUser[userID][q.ID]; ok && mine != "" {
			v.MyAnswer = &mine
		}
		if bothDone {
			honest := byUser[subject][q.ID]
			guess := byUser[guesser][q.ID]
			v.HonestAnswer = &honest
			v.Guess = &guess
			v.Matched = honest != "" && honest == guess
			if v.Matched {
				matches++
			}
		}
		views = append(views, v)
	}
	score := 0
	if bothDone && len(questions) > 0 {
		score = matches * 100 / len(questions)
	}

	writeJSON(w, http.StatusOK, hwdykmPackDetail{
		ID: pack.ID, Title: pack.Title, Icon: pack.Icon, ColorKey: pack.ColorKey, Tag: pack.Tag,
		MyDone: myDone, BothDone: bothDone, Score: score, Questions: views,
	})
}

// POST /v1/games/hwdykm/packs/{id}/answer  { questionId, answer }
func (d Deps) handleAnswerHwdykmPack(w http.ResponseWriter, r *http.Request) {
	userID, ok := d.authedUser(w, r)
	if !ok {
		return
	}
	c, ok := d.gameCouple(w, r, userID)
	if !ok {
		return
	}
	pack, found := findHwdykmPack(chi.URLParam(r, "id"))
	if !found {
		writeError(w, http.StatusNotFound, "unknown_pack", "unknown pack")
		return
	}
	var req struct {
		QuestionID string `json:"questionId"`
		Answer     string `json:"answer"`
	}
	if !decodeJSON(w, r, &req) {
		return
	}
	gen, questions, _, _, err := d.hwdykmRoundQuestions(r.Context(), c.ID, pack, langParam(r))
	if err != nil {
		d.serverError(w, "hwdykm: round", err)
		return
	}
	var question *hwdykmQuestion
	for i := range questions {
		if questions[i].ID == req.QuestionID {
			question = &questions[i]
			break
		}
	}
	if question == nil {
		writeError(w, http.StatusBadRequest, "unknown_question", "unknown question")
		return
	}
	answer := strings.TrimSpace(req.Answer)
	validOption := false
	for _, o := range question.Options {
		if o.ID == answer {
			validOption = true
			break
		}
	}
	if !validOption {
		writeError(w, http.StatusBadRequest, "unknown_option", "unknown option")
		return
	}
	quizID := hwdykmAnswerKey(pack.ID, gen)
	if err := d.Store.UpsertQuizAnswer(r.Context(), c.ID, quizID, req.QuestionID, userID, answer); err != nil {
		d.serverError(w, "hwdykm: save", err)
		return
	}
	d.notifyTurnOrResults(r.Context(), c.ID, userID, quizID,
		"How Well Do You Know Me", len(questions),
		"You've both finished "+pack.Title+" — see your score 💛",
		map[string]string{"type": "hwdykm", "packId": pack.ID})
	w.WriteHeader(http.StatusNoContent)
}

// POST /v1/games/hwdykm/packs/{id}/seen
//
// Client calls this when the reveal screen opens. Once both partners have
// seen results for the current round (and both have answered every question),
// the round is retired and the next fetch produces a fresh batch of questions.
func (d Deps) handleSeenHwdykmPack(w http.ResponseWriter, r *http.Request) {
	userID, ok := d.authedUser(w, r)
	if !ok {
		return
	}
	c, ok := d.gameCouple(w, r, userID)
	if !ok {
		return
	}
	pack, found := findHwdykmPack(chi.URLParam(r, "id"))
	if !found {
		writeError(w, http.StatusNotFound, "unknown_pack", "unknown pack")
		return
	}
	partner, _ := d.Store.GetPartner(r.Context(), c.ID, userID)

	gen, questions, st, rs, err := d.hwdykmRoundQuestions(r.Context(), c.ID, pack, langParam(r))
	if err != nil {
		d.serverError(w, "hwdykm: round", err)
		return
	}
	quizID := hwdykmAnswerKey(pack.ID, gen)
	answers, err := d.Store.GetQuizAnswers(r.Context(), c.ID, quizID)
	if err != nil {
		d.serverError(w, "hwdykm: answers", err)
		return
	}
	answered := make(map[string]map[string]bool)
	for _, a := range answers {
		if answered[a.UserID] == nil {
			answered[a.UserID] = make(map[string]bool)
		}
		answered[a.UserID][a.QuestionID] = true
	}
	bothDone := partner.ID != ""
	for _, q := range questions {
		if !answered[userID][q.ID] || (partner.ID != "" && !answered[partner.ID][q.ID]) {
			bothDone = false
			break
		}
	}
	if !bothDone {
		if !contains(st.SeenBy, userID) {
			st.SeenBy = append(st.SeenBy, userID)
			_ = rs.save(r.Context(), st)
		}
		w.WriteHeader(http.StatusNoContent)
		return
	}

	_, bothSeen, err := rs.markSeen(r.Context(), userID, partner.ID)
	if err != nil {
		d.serverError(w, "hwdykm: seen", err)
		return
	}
	if bothSeen {
		fresh := d.generateFreshHwdykmQuestions(r.Context(), pack, langParam(r), gen+1)
		raw, _ := json.Marshal(hwdykmRoundContent{Questions: fresh})
		if _, err := rs.bumpGeneration(r.Context(), raw); err != nil {
			d.serverError(w, "hwdykm: bump", err)
			return
		}
	}
	w.WriteHeader(http.StatusNoContent)
}
